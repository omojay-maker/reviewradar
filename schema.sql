-- ---------------------------------------------------------------------------
-- ReviewRadar - Multi-Tenant VoC / Sentiment Platform
-- PostgreSQL 13+ (JSONB expansion used by analytics queries)
-- Idempotent: safe to run on every deploy.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- companies: one row per SaaS tenant (multi-tenant boundary = company_id)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS companies (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    slug          VARCHAR(191) NOT NULL,
    email         VARCHAR(191) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    api_key       VARCHAR(64)  NOT NULL,
    is_active     SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_companies_slug UNIQUE (slug),
    CONSTRAINT uq_companies_email UNIQUE (email),
    CONSTRAINT uq_companies_api_key UNIQUE (api_key)
);

CREATE INDEX IF NOT EXISTS idx_companies_is_active ON companies (is_active);

-- ---------------------------------------------------------------------------
-- reviews: raw review text + Groq structured analysis, scoped to one tenant
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reviews (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      INTEGER       NOT NULL,
    source          VARCHAR(32)   NOT NULL DEFAULT 'api',
    external_id     VARCHAR(191)  DEFAULT NULL,
    author_name     VARCHAR(255)  DEFAULT NULL,
    rating          NUMERIC(3, 1) DEFAULT NULL,
    source_url      VARCHAR(500)  DEFAULT NULL,
    raw_text        TEXT          NOT NULL,
    sentiment       VARCHAR(16)   NOT NULL CHECK (sentiment IN ('positive', 'neutral', 'negative')),
    score           NUMERIC(4, 3) NOT NULL CHECK (score >= -1.000 AND score <= 1.000),
    categories      JSONB         NOT NULL DEFAULT '[]'::jsonb,
    summary         VARCHAR(512)  NOT NULL,
    requires_action SMALLINT      NOT NULL DEFAULT 0 CHECK (requires_action IN (0, 1)),
    model           VARCHAR(64)   NOT NULL,
    analyzed_at     TIMESTAMP     NOT NULL DEFAULT NOW(),
    created_at      TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_reviews_company_external UNIQUE (company_id, external_id),
    CONSTRAINT fk_reviews_company
        FOREIGN KEY (company_id) REFERENCES companies (id)
            ON DELETE CASCADE
            ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_reviews_company_created ON reviews (company_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reviews_company_sentiment ON reviews (company_id, sentiment);
CREATE INDEX IF NOT EXISTS idx_reviews_company_urgent ON reviews (company_id, requires_action, created_at);

